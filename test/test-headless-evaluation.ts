// Test 7: Headless 3x3 Threat Matrix & Field Enemy Distribution Simulation
console.log('Testing 7: Headless 3x3 Threat Matrix & Field Enemy Distribution Simulation...');
{
  const simulationEngine = new GameEngine();
  simulationEngine.startGame();
  const simPlayer = simulationEngine.getPlayer();
  const simDragon = simulationEngine.getDragon();

  // 1. STR特化（ガラスの剣: 高STR・低EXP・低HP）状態のシミュレーション
  simPlayer.holdItem = 'NONE';
  simPlayer.hasSword = true;
  simPlayer.strength = 3500;  // effectiveAttack = 4500 (サウルス含む通常敵を一撃粉砕可能)
  simPlayer.experience = 50;  // 守備力ほぼ皆無
  simPlayer.hp = 150;         // HPが低く、中位以上の敵の先制攻撃で即死する

  // 初期スポーンの偏りに依存せず確実にONE_SHOT対象を検証できるようテスト敵を保証追加
  simulationEngine.addEnemy(new EnemyInstance({ typeId: 1, pos: { x: 1, y: 1 } }));

  const enemies = simulationEngine.getEnemies().filter(e => e.isAlive);
  const targets = [...enemies, ...simDragon.heads.filter(h => h.isAlive)];

  assert.ok(targets.length > 0, 'Field must contain active target enemies and dragon heads');

  interface MatrixStats {
    matrix: Record<string, number>;
    totalEvaluated: number;
    safeOneShot: number;
    riskyOneShot: number;
    lethalOneShot: number;
  }

  const stats: MatrixStats = {
    matrix: {},
    totalEvaluated: 0,
    safeOneShot: 0,
    riskyOneShot: 0,
    lethalOneShot: 0,
  };

  for (const target of targets) {
    const details = ThreatEvaluator.evaluateThreatDetails(simPlayer, target);

    // 整合性チェック: NaN や異常値がないこと
    assert.ok(!isNaN(details.damageToEnemy), 'damageToEnemy must be a valid number');
    assert.ok(!isNaN(details.damageToPlayer), 'damageToPlayer must be a valid number');
    assert.ok(details.turnsToKill >= 1, 'turnsToKill must be >= 1');

    const key = `${details.attackThreat} x ${details.defenseThreat}`;
    stats.matrix[key] = (stats.matrix[key] || 0) + 1;
    stats.totalEvaluated++;

    if (details.attackThreat === 'ONE_SHOT') {
      if (details.defenseThreat === 'NO_DAMAGE') {
        stats.safeOneShot++;
      } else if (details.defenseThreat === 'TAKES_DAMAGE') {
        stats.riskyOneShot++;
        assert.strictEqual(details.isRiskyOneShot, true, 'isRiskyOneShot must be true for ONE_SHOT x TAKES_DAMAGE');
      } else if (details.defenseThreat === 'LETHAL') {
        stats.lethalOneShot++;
        assert.strictEqual(details.isLethalOneShot, true, 'isLethalOneShot must be true for ONE_SHOT x LETHAL');
      }
    }
  }

  console.log(`[Headless 3x3 Matrix Distribution in Glass-Cannon State]`);
  console.log(`- Total Targets Evaluated: ${stats.totalEvaluated}`);
  console.log(`- Safe One-Shots (ONE_SHOT x NO_DAMAGE)  : ${stats.safeOneShot}`);
  console.log(`- Risky One-Shots (ONE_SHOT x TAKES_DMG): ${stats.riskyOneShot}`);
  console.log(`- Lethal One-Shots (ONE_SHOT x LETHAL)  : ${stats.lethalOneShot}`);
  for (const [key, count] of Object.entries(stats.matrix)) {
    console.log(`   * ${key.padEnd(28)}: ${count}`);
  }

  // 評価総数が対象数と完全に一致すること
  assert.strictEqual(stats.totalEvaluated, targets.length, 'All targets must be evaluated');

  // STR=2000, EXP=50, HP=150 では、ワンパンできるが敵先制なら被ダメ・即死となる敵が存在することを検証
  // （もし敵の強さバリエーションによりどちらかが0でも、マトリクス集計が正しく稼働していることを確認）
  assert.ok(stats.safeOneShot + stats.riskyOneShot + stats.lethalOneShot > 0, 'At least some one-shots should exist with 3000 attack');

  console.log('✓ 7. Headless 3x3 threat matrix & field distribution simulation verified successfully.');
}

